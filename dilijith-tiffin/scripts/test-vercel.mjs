import assert from 'node:assert/strict';
import http from 'node:http';
import mongoose from 'mongoose';
import { randomUUID } from 'node:crypto';
import { MongoMemoryServer } from 'mongodb-memory-server';
import { connectDB } from '../server/config/db.js';
import { validateEnvironment } from '../server/config/environment.js';
import handler from '../api/index.js';
process.env.NODE_ENV = 'production';
process.env.JWT_SECRET = randomUUID();
process.env.ALLOWED_ORIGIN = 'https://tiffin.example';
delete process.env.MONGODB_URI;
assert.throws(validateEnvironment);
await assert.rejects(connectDB);
const db = await MongoMemoryServer.create();
const originalConnect = mongoose.connect;
let calls = 0;
mongoose.connect = function (...args) { calls++; return originalConnect.apply(this, args); };
let server;
try {
  process.env.MONGODB_URI = db.getUri();
  process.env.MONGODB_DB_NAME = 'dts_vercel_test';
  validateEnvironment();
  const secret = process.env.JWT_SECRET;
  process.env.JWT_SECRET = 'replace_this_placeholder_secret_123456';
  assert.throws(validateEnvironment);
  process.env.JWT_SECRET = secret;
  mongoose.connect = () => { calls++; return Promise.reject(new Error('private database detail')); };
  await assert.rejects(connectDB);
  mongoose.connect = function (...args) { calls++; return originalConnect.apply(this, args); };
  await Promise.all(Array.from({ length: 8 }, () => connectDB()));
  assert.equal(calls, 2, 'failed connection must retry; concurrent requests share one connection');
  await connectDB(); assert.equal(calls, 2);
  server = http.createServer(handler).listen(0);
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://localhost:${server.address().port}`;
  const health = await fetch(base + '/api/health');
  assert.equal(health.status, 200); assert.equal((await health.json()).database.connected, true);
  assert.equal(health.headers.get('cache-control'), 'no-store');
  const missing = await fetch(base + '/api/unknown');
  assert.equal(missing.status, 404); assert.equal((await missing.json()).ok, false);
  assert.equal((await fetch(base + '/api/auth/me')).status, 401);
  assert.equal((await fetch(base + '/api/auth/logout', { method: 'POST', headers: { Origin: 'https://hostile.example' } })).status, 403);
  const malformed = await fetch(base + '/api/auth/login', { method: 'POST', headers: { Origin: process.env.ALLOWED_ORIGIN, 'Content-Type': 'application/json' }, body: '{' });
  assert.equal(malformed.status, 400); assert.equal((await malformed.json()).message, 'Invalid JSON request body.');
  await mongoose.disconnect();
  delete process.env.MONGODB_URI;
  const unavailable = await fetch(base + '/api/health');
  assert.equal(unavailable.status, 503); assert.equal((await unavailable.json()).database.connected, false);
  process.env.MONGODB_URI = db.getUri();
  assert.equal((await fetch(base + '/api/health')).status, 200);
  assert.equal(await mongoose.connection.db.collection('users').countDocuments(), 0, 'initialization never seeds users');
  console.log('Vercel handler tests passed: connection reuse/retry, env validation, health, JSON errors, auth, CSRF and no seeding.');
} finally {
  mongoose.connect = originalConnect;
  if (server) await new Promise(resolve => server.close(resolve));
  await mongoose.disconnect(); await db.stop();
}
